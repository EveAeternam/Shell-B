async def generate_voice(args, ctx):
    lines = args.get("lines")
    if not lines:
        text = str(args.get("text") or "").strip()
        if not text:
            return ToolResult("Give text (one line) or lines (a list of {id, text, voice}).", error=True)
        lines = [{"id": args.get("save_as") or slug(text, "line"), "text": text, "voice": args.get("voice")}]
    if not isinstance(lines, list) or len(lines) > 40:
        return ToolResult("lines must be a list of at most 40 {id, text, voice} objects.", error=True)
    speed = max(0.5, min(2.0, float(args.get("speed") or 1.0)))
    urls, results = [], []
    async with httpx.AsyncClient(timeout=180) as c:
        for ln in lines:
            if not isinstance(ln, dict) or not str(ln.get("text") or "").strip():
                continue
            voice = str(ln.get("voice") or args.get("voice") or "af_heart")
            r = await c.post(f"{HERMES}/tts", json={"text": str(ln["text"]), "voice": voice,
                                                    "speed": float(ln.get("speed") or speed), "format": "wav"})
            if r.status_code >= 400:
                return ToolResult(f"HERMES failed on {ln.get('id')!r}: {r.text[:300]}", error=True)
            wav = trim_and_fade(r.content, fade_ms=5, thresh_db=-50)
            ident = str(ln.get("id") or slug(str(ln["text"]), "line"))
            explicit = ident if "/" in ident else ""
            try:
                rel, url = await save_output(ctx, wav, f"assets/audio/voice/{slug(ident, 'line')}.wav", ".wav", explicit)
            except ValueError as e:
                return ToolResult(str(e), error=True)
            urls.append(url)
            results.append(f"{rel or url} [{voice}, {_duration(wav):.1f}s]")
    if not urls:
        return ToolResult("No lines had text.", error=True)
    return ToolResult(f"Synthesized {len(urls)} voice line(s) with Kokoro (24 kHz): {'; '.join(results)}. Players are shown to "
                      "the user. Kokoro reads plain text: spell out numbers and acronyms the way they should be spoken, "
                      "and use punctuation for pacing. " + VOICE_HINT,
                      {"audio": urls[:12], "prompt": "; ".join(str(ln.get("text"))[:60] for ln in lines[:3])})


# ── sprites (FLUX → BiRefNet cut-out → trimmed RGBA) ────────────────────────

SPRITE_STYLE = (", a single isolated game asset, the entire subject in frame and centered with margin around it, on a plain "
                "flat solid {bg} background, no ground, no cast shadow, no text, no border")


def _cutout(rgb: bytes, mask: bytes, size: int | None, pixel: int | None, colors: int | None) -> tuple[bytes, tuple]:
    from PIL import Image
    im = Image.open(io.BytesIO(rgb)).convert("RGB")
    m = Image.open(io.BytesIO(mask)).convert("L").resize(im.size)
    rgba = im.copy()
    rgba.putalpha(m)
    box = m.point(lambda v: 255 if v > 24 else 0).getbbox()
    if box:
        pad = max(4, (box[2] - box[0] + box[3] - box[1]) // 40)
        box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
        rgba = rgba.crop(box)
    if pixel:  # pixel art: shrink to the grid with a box filter, harden alpha, cut the palette
        w, h = rgba.size
        scale = pixel / max(w, h)
        small = rgba.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.BOX)
        a = small.split()[3].point(lambda v: 255 if v >= 128 else 0)
        rgb_small = small.convert("RGB").quantize(colors=colors or 16, method=Image.Quantize.MEDIANCUT).convert("RGB")
        small = rgb_small.copy()
        small.putalpha(a)
        rgba = small
    elif size:
        rgba.thumbnail((size, size), Image.LANCZOS)
    out = io.BytesIO()
    rgba.save(out, "PNG", optimize=True)
    return out.getvalue(), rgba.size


def _checker_preview(png: bytes, scale_to: int = 512) -> bytes:
    """The sprite over a checkerboard, upscaled nearest-neighbour, so a vision model can judge the cut-out."""
    from PIL import Image
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    k = max(1, scale_to // max(im.size))
    im = im.resize((im.width * k, im.height * k), Image.NEAREST)
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    cell = max(8, im.width // 16)
    px = bg.load()
    for y in range(im.height):
        for x in range(im.width):
            if (x // cell + y // cell) % 2:
                px[x, y] = (204, 204, 204, 255)
    bg.alpha_composite(im)
    out = io.BytesIO()
    bg.convert("RGB").save(out, "PNG")
    return out.getvalue()


async def _flux_png(c, prompt, width, height, seed, extra: dict | None = None, quality: str = "draft") -> dict:
    wf = _flux_workflow(prompt, width, height, seed, quality)
    if extra:
        wf.update(extra)
    outputs = await _comfy_run(c, wf, 600)

    async def fetch(item):
        return (await c.get(f"{COMFY}/view", params={"filename": item["filename"], "subfolder": item.get("subfolder", ""),
                                                     "type": item.get("type", "output")})).content
    return {k: await fetch(v["images"][0]) for k, v in outputs.items() if v.get("images")}


