async def _stable_audio_up() -> bool:
    try:
        async with httpx.AsyncClient(timeout=2) as c:
            return (await c.get(f"{STABLE_AUDIO}/health")).status_code == 200
    except httpx.HTTPError:
        return False


def slug(text: str, fallback: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (text or "").lower())[:40].strip("-") or fallback


async def save_output(ctx, data: bytes, default_rel: str, ext: str, save_as: str = "") -> tuple[str | None, str]:
    """Write generated bytes into the project (returns its relative path and raw URL) or into /api/files.
    Raises ValueError when save_as escapes the project."""
    if ctx.project_id:
        root = (db.DATA / "projects" / ctx.project_id).resolve()
        want = (save_as or "").strip().lstrip("/") or default_rel
        want = re.sub(r"\.\w+$", "", want) + ext
        dest = (root / want).resolve()
        if not str(dest).startswith(str(root) + "/"):
            raise ValueError(f"save_as must stay inside the project: {want!r}")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
        await ctx.emit({"type": "file", "path": want, "action": "created"})
        return want, f"/api/projects/{ctx.project_id}/raw/{want}"
    name = f"{default_rel.rsplit('/', 1)[-1].rsplit('.', 1)[0]}-{uuid.uuid4().hex[:8]}{ext}"
    (FILES / name).write_bytes(data)
    return None, f"/api/files/{name}"


# ── audio post-processing (numpy + soundfile) ───────────────────────────────

def _read(wav: bytes):
    import soundfile as sf
    data, sr = sf.read(io.BytesIO(wav), dtype="float32", always_2d=True)
    return data, sr


def _write(data: np.ndarray, sr: int, normalize: bool = False) -> bytes:
    import soundfile as sf
    peak = float(np.abs(data).max()) if data.size else 0
    if peak > 0.891 or (normalize and peak > 1e-4):  # -1 dBFS
        data = data * (0.891 / peak)
    buf = io.BytesIO()
    sf.write(buf, data, sr, format="WAV", subtype="PCM_16")
    return buf.getvalue()


def trim_and_fade(wav: bytes, fade_ms: float = 8, thresh_db: float = -45) -> bytes:
    """Trim leading/trailing near-silence (one-shot SFX should start on the transient) and add tiny fades against clicks."""
    data, sr = _read(wav)
    env = np.abs(data).max(axis=1)
    thresh = 10 ** (thresh_db / 20) * max(float(env.max()), 1e-9)
    loud = np.nonzero(env > thresh)[0]
    if loud.size:
        start = max(0, loud[0] - int(sr * 0.005))
        end = min(len(data), loud[-1] + int(sr * 0.05))
        data = data[start:end]
    n = min(int(sr * fade_ms / 1000), len(data) // 4)
    if n > 1:
        ramp = np.linspace(0, 1, n, dtype=np.float32)[:, None]
        data[:n] *= ramp
        data[-n:] *= ramp[::-1]
    return _write(data, sr, normalize=True)  # consistent levels across a sound set


def make_loop(wav: bytes, xfade_s: float = 1.0) -> bytes:
    """Crossfade the tail into the head (equal power) so the clip loops without a seam."""
    data, sr = _read(wav)
    n = min(int(sr * xfade_s), len(data) // 3)
    if n < 16:
        return wav
    t = np.linspace(0, np.pi / 2, n, dtype=np.float32)[:, None]
    head, tail = data[:n], data[-n:]
    blended = tail * np.cos(t) + head * np.sin(t)
    out = np.concatenate([blended, data[n:-n]])
    return _write(out, sr, normalize=True)


def _duration(wav: bytes) -> float:
    data, sr = _read(wav)
    return len(data) / sr


