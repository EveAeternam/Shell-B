async def generate_sfx(args, ctx):
    prompt = str(args.get("prompt") or "").strip()
    if not prompt:
        return ToolResult("Describe the sound: source, action, material, space, e.g. 'heavy wooden door slams in a stone hall'.",
                          error=True)
    loop = bool(args.get("loop"))
    want = str(args.get("engine") or "auto").lower()
    stable = want in ("auto", "stable", "stable-audio") and await _stable_audio_up()
    fell_back = want in ("stable", "stable-audio") and not stable
    duration = max(0.5, min(46.0 if stable else 30.0, float(args.get("duration") or 3)))
    variations = max(1, min(4, int(args.get("variations") or 1)))
    evicted = await make_room(14 if stable else 10, {ctx.agent.get("model", "")})
    results, urls, saved = [], [], []
    base = slug(prompt, "sfx")
    t0 = time.time()
    async with httpx.AsyncClient(timeout=600) as c:
        for i in range(variations):
            if stable:
                r = await c.post(f"{STABLE_AUDIO}/generate", json={"prompt": prompt, "duration": duration + (1.0 if loop else 0)})
            else:
                r = await c.post(f"{ORPHEUS}/generate/sfx", json={"prompt": prompt, "duration": duration + (1.0 if loop else 0)})
            if r.status_code >= 400:
                return ToolResult(f"{'Stable Audio' if stable else 'ORPHEUS'} failed: {r.text[:500]}", error=True)
            wav = make_loop(r.content) if loop else trim_and_fade(r.content)
            sub = "ambience" if loop else "sfx"
            suffix = f"-{i + 1}" if variations > 1 else ""
            save_as = str(args.get("save_as") or "")
            if save_as and variations > 1:
                save_as = re.sub(r"(\.\w+)?$", f"{suffix}.wav", save_as, count=1)
            try:
                rel, url = await save_output(ctx, wav, f"assets/audio/{sub}/{base}{suffix}.wav", ".wav", save_as)
            except ValueError as e:
                return ToolResult(str(e), error=True)
            urls.append(url)
            results.append(f"{rel or url} ({_duration(wav):.2f}s)")
            if rel:
                saved.append(rel)
    if stable:  # hand its ~6 GB back to the language models
        async with httpx.AsyncClient(timeout=30) as c:
            try:
                await c.post(f"{STABLE_AUDIO}/unload")
            except httpx.HTTPError:
                pass
    note = f" (evicted idle models to make room: {', '.join(evicted)})" if evicted else ""
    if fell_back:
        note += " (Stable Audio is not running, so this used AudioGen.)"
    engine = "Stable Audio Open (44.1 kHz stereo)" if stable else "AudioGen (16 kHz mono)"
    model = "stabilityai/stable-audio-open-1.0" if stable else "facebook/audiogen-medium"
    how = ("Seamless loop: play it with loop=true (an <audio loop> element, or WebAudio with source.loop = true). "
           if loop else "Trimmed to start on the sound, with tiny fades. ")
    return ToolResult(f"Generated {variations} sound effect(s) with {engine} in {time.time() - t0:.0f}s: "
                      f"{', '.join(results)}. {how}Players are shown to the user; don't link them. For games, preload each "
                      "file once with fetch + AudioContext.decodeAudioData and play it through a shared gain node (mute "
                      "toggle), detuning it slightly per play (playbackRate 0.95-1.05) so repeats don't sound robotic. "
                      "Listen-test isn't possible for you: tell the user which sounds to audition." + note,
                      {"audio": urls, "prompt": prompt, "audioInfo": {"model": model, "prompt": prompt}})


